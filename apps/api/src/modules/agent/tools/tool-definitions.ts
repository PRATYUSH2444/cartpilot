export interface ToolDefinition<TInput = any, TOutput = any> {
  name: string;
  description: string;
  schema: z.ZodSchema<TInput>;
  parametersJsonSchema: Record<string, any>;
  execute: (input: TInput, context: { userId: string }) => Promise<TOutput>;
}

// 1. matchIngredientsToCatalog Tool (Dynamic Ingredient Intelligence)
const MatchIngredientsInputSchema = z.object({
  dishName: z.string().min(1).default('Custom Recipe'),
  servings: z.coerce.number().int().positive().max(50).default(4),
  cuisine: z.string().optional().default('Vegetarian'),
  instructions: z.array(z.string()).optional(),
  ingredients: z
    .array(
      z.object({
        name: z.string().min(1, 'Ingredient name is required'),
        quantity: z.coerce.number().positive('Quantity must be positive'),
        unit: z.string().default('G'),
        isMandatory: z.boolean().optional().default(true),
        suggestedAlternative: z.string().optional(),
      })
    )
    .min(1, 'At least one ingredient must be provided'),
});

export const matchIngredientsToCatalogTool: ToolDefinition = {
  name: 'matchIngredientsToCatalog',
  description:
    'Match ANY dynamic list of culinary ingredients (generated by the AI for any regional, Indian, or international dish) against the live merchant catalogue in MongoDB. Verifies stock, computes required pack counts without partial packages, identifies missing store items, and discovers culinary alternatives.',
  schema: MatchIngredientsInputSchema,
  parametersJsonSchema: {
    type: 'object',
    properties: {
      dishName: { type: 'string', description: 'Name of the dish or meal being planned' },
      servings: { type: 'integer', description: 'Number of people/servings to prepare', default: 4 },
      cuisine: { type: 'string', description: 'Cuisine style (e.g. "Indo-Chinese", "Bengali", "North Indian", "Italian")' },
      instructions: {
        type: 'array',
        items: { type: 'string' },
        description: 'Brief step-by-step culinary preparation instructions',
      },
      ingredients: {
        type: 'array',
        items: {
          type: 'object',
          properties: {
            name: { type: 'string', description: 'Ingredient name (e.g. "Button Mushrooms", "Green Capsicum", "Soy Sauce", "Besan")' },
            quantity: { type: 'number', description: 'Culinary quantity required' },
            unit: { type: 'string', description: 'Unit (G, KG, ML, L, PIECE, TBSP, TSP, CUP)' },
            isMandatory: { type: 'boolean', description: 'Whether the ingredient is essential or optional garnish' },
            suggestedAlternative: { type: 'string', description: 'Optional suggested culinary substitute' },
          },
          required: ['name', 'quantity'],
        },
        description: 'List of all required recipe ingredients',
      },
    },
    required: ['dishName', 'ingredients'],
  },
  execute: async (input, _context) => {
    return IngredientIntelligenceService.matchIngredientsToCatalog(
      input.ingredients,
      input.dishName,
      input.servings,
      input.cuisine,
      input.instructions
    );
  },
};

// 2. searchCatalog Tool
const SearchCatalogInputSchema = z.object({
  query: z.string().min(1, 'Search query cannot be empty').trim(),
  category: productCategoryEnum.optional(),
  limit: z.coerce.number().int().min(1).max(20).default(6),
});

export const searchCatalogTool: ToolDefinition = {
  name: 'searchCatalog',
  description:
    'Search the certified vegetarian grocery catalog by product name, category, or alias keywords (e.g. "paneer", "basmati", "pyaz", "ghee", "mushrooms").',
  schema: SearchCatalogInputSchema,
  parametersJsonSchema: {
    type: 'object',
    properties: {
      query: { type: 'string', description: 'Search term or product alias' },
      category: {
        type: 'string',
        enum: [
          'GRAINS',
          'PULSES',
          'DAIRY',
          'VEGETABLES',
          'SPICES',
          'OILS',
          'CONDIMENTS',
          'FRUITS_VEGETABLES',
          'DAIRY_BREAKFAST',
          'ATTA_RICE_DAL',
          'SNACKS_MUNCHIES',
          'COLD_DRINKS_JUICES',
          'BAKERY',
          'INSTANT_FROZEN_FOOD',
          'MASALA_DRY_FRUITS',
          'PERSONAL_CARE',
          'HOUSEHOLD_ESSENTIALS',
          'BABY_CARE',
          'PET_CARE',
        ],
        description: 'Optional category filter',
      },
      limit: { type: 'integer', description: 'Max items to return (1-20)', default: 6 },
    },
    required: ['query'],
  },
  execute: async (input, _context) => {
    const result = await CatalogService.searchCatalog({
      page: 1,
      query: input.query,
      category: input.category as ProductCategory,
      limit: input.limit,
    });

    return {
      totalFound: result.total,
      products: result.products.map((p) => ({
        id: p._id.toString(),
        name: p.name,
        category: p.category,
        packageSize: p.packageSize,
        packageUnit: p.packageUnit,
        pricePaise: p.pricePaise,
        formattedPrice: PricingService.formatPaise(p.pricePaise),
        availableStock: p.availableStock,
        aliases: p.aliases,
      })),
    };
  },
};

